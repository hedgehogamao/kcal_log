// Foundation/ICU Mandarin-Latin transliteration, basic CJK and Extension A.
// This is a search index only, never a food translation or nutritional equivalence.
import Foundation
print("// Generated by tool/build_pinyin_index.swift using Foundation/ICU Mandarin-Latin.\n// Search only. Unknown characters remain literal; food phrases override polyphony.\nconst pinyinData = <int, String>{")
var count = 0
for code in 0x3400...0x9fff {
  let original = String(UnicodeScalar(code)!)
  var value = original.applyingTransform(.mandarinToLatin, reverse: false) ?? original
  for vowel in ["ü", "ǖ", "ǘ", "ǚ", "ǜ"] { value = value.replacingOccurrences(of: vowel, with: "v") }
  value = (value.applyingTransform(.stripCombiningMarks, reverse: false) ?? value).lowercased()
  if value.range(of: "^[a-z]+$", options: .regularExpression) != nil {
    print("  \(code): '\(value)',"); count += 1
  }
}
print("}; // \(count) indexed characters")
